function createPreferenceControls() {
    if (document.querySelector('.app-preferences')) return;

    const wrapper = document.createElement('div');
    wrapper.className = 'app-preferences';
    wrapper.innerHTML = `
        <button type="button" class="app-pref-btn" id="themeToggle"></button>
        <button type="button" class="app-pref-btn" id="languageToggle"></button>
    `;
    document.body.appendChild(wrapper);

    document.getElementById('themeToggle').addEventListener('click', () => {
        const nextTheme = getPreference('theme', 'light') === 'dark' ? 'light' : 'dark';
        setPreference('theme', nextTheme);
        applyPreferences();
    });

    document.getElementById('languageToggle').addEventListener('click', () => {
        const nextLanguage = getPreference('language', 'en') === 'ms' ? 'en' : 'ms';
        setPreference('language', nextLanguage);
        applyPreferences();
    });
}

function getPreference(key, fallback) {
    return localStorage.getItem(`shmaas_${key}`) || fallback;
}

function setPreference(key, value) {
    localStorage.setItem(`shmaas_${key}`, value);
}

function rememberOriginals() {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
        acceptNode(node) {
            const parent = node.parentElement;
            if (!parent || ['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(parent.tagName)) {
                return NodeFilter.FILTER_REJECT;
            }
            return node.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
        }
    });

    const nodes = [];
    while (walker.nextNode()) {
        nodes.push(walker.currentNode);
    }

    nodes.forEach(node => {
        if (!APP_TEXT_NODES.some(entry => entry.node === node)) {
            APP_TEXT_NODES.push({
                node,
                original: node.nodeValue
            });
        }
    });

    document.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(element => {
        if (!element.dataset.originalPlaceholder) {
            element.dataset.originalPlaceholder = element.getAttribute('placeholder');
        }
    });
}

function translatePage(language) {
    const dictionary = APP_TRANSLATIONS[language] || {};
    const placeholderDictionary = APP_PLACEHOLDER_TRANSLATIONS[language] || {};

    APP_TEXT_NODES.forEach(entry => {
        const trimmedOriginal = entry.original.trim();
        const translated = language === 'en' ? trimmedOriginal : dictionary[trimmedOriginal];
        if (translated) {
            const leading = entry.original.match(/^\s*/)?.[0] || '';
            const trailing = entry.original.match(/\s*$/)?.[0] || '';
            entry.node.nodeValue = `${leading}${translated}${trailing}`;
        } else {
            entry.node.nodeValue = entry.original;
        }
    });

    document.querySelectorAll('[data-original-placeholder]').forEach(element => {
        const original = element.dataset.originalPlaceholder;
        const translated = language === 'en' ? original : placeholderDictionary[original];
        element.setAttribute('placeholder', translated || original);
    });
}

function updatePreferenceLabels() {
    const theme = getPreference('theme', 'light');
    const language = getPreference('language', 'en');
    const themeToggle = document.getElementById('themeToggle');
    const languageToggle = document.getElementById('languageToggle');

    if (themeToggle) {
        themeToggle.textContent = theme === 'dark'
            ? (language === 'ms' ? '☀️ Tema Cerah' : '☀️ Light Theme')
            : (language === 'ms' ? '🌙 Tema Gelap' : '🌙 Dark Theme');
    }

    if (languageToggle) {
        languageToggle.textContent = language === 'ms' ? '🇬🇧 English' : '🇲🇾 Melayu';
    }
}

function applyPreferences() {
    const theme = getPreference('theme', 'light');
    const language = getPreference('language', 'en');

    document.documentElement.dataset.theme = theme;
    document.documentElement.lang = language === 'ms' ? 'ms' : 'en';
    rememberOriginals();
    translatePage(language);
    updatePreferenceLabels();
}

document.addEventListener('DOMContentLoaded', () => {
    injectPreferenceStyles();
    createPreferenceControls();
    applyPreferences();
});
